export function getInitialLanguage() {
  const params = new URLSearchParams(window.location.search)
  const urlLanguage = normalizeLanguage(params.get('ui_lang'))
  if (urlLanguage) return urlLanguage

  const savedLanguage = normalizeLanguage(readSavedLanguage())
  if (savedLanguage) return savedLanguage

  for (const browserLanguage of navigator.languages || [navigator.language]) {
    const normalized = normalizeLanguage(browserLanguage)
    if (normalized) return normalized
  }
  return 'en'
}

export function setInterfaceLanguage(language) {
  const normalized = normalizeLanguage(language) || 'en'
  try {
    window.localStorage.setItem(STORAGE_KEY, normalized)
  } catch {
    // The URL remains the durable fallback when storage is unavailable.
  }
  const params = new URLSearchParams(window.location.search)
  params.set('ui_lang', normalized)
  replaceUrl(params)
  return normalized
}

export function translate(language, key, values = {}) {
  const template = translations[language]?.[key] ?? translations.en[key] ?? key
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  )
}

function normalizeLanguage(language) {
  if (!language) return null
  const value = String(language).trim()
  if (SUPPORTED_LANGUAGES.includes(value)) return value
  const lower = value.toLowerCase()
  if (lower === 'zh-hans' || lower === 'zh-cn' || lower === 'zh-sg' || lower === 'zh') return 'zh-Hans'
  if (lower === 'es' || lower.startsWith('es-')) return 'es'
  if (lower === 'ko' || lower.startsWith('ko-')) return 'ko'
  if (lower === 'en' || lower.startsWith('en-')) return 'en'
  return null
}

function readSavedLanguage() {
  try {
    return window.localStorage.getItem(STORAGE_KEY)
  } catch {
    return null
  }
}

function replaceUrl(params) {
  const query = params.toString()
  const hash = window.location.hash
  window.history.replaceState(
    null,
    '',
    `${window.location.pathname}${query ? `?${query}` : ''}${hash}`,
  )
}
